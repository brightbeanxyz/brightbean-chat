export type BuilderTranslations = typeof en;

/**
 * `en.ts`'s shape, loosened for `ru.ts`/`ky.ts`.
 *
 * Russian's four CLDR plural categories and Kyrgyz's one both differ from
 * English's two, so a locale file legitimately defines a different set of
 * `_one`/`_few`/`_many`/`_other` siblings than `en.ts` does for the same
 * counted phrase — every leaf is therefore optional, and an index signature
 * admits a suffix `en.ts` never declares (`_few`/`_many` for `ru.ts`). The
 * exact set that actually has to match — every plural *family*, and that no
 * leaf is left copy-pasted from English — is enforced at runtime by
 * `./shape.test.ts`, which is the more precise check for this than the
 * type system easily expresses.
 */
export type LooseTranslations<T> = {
  [K in keyof T]?: T[K] extends string ? string : LooseTranslations<T[K]>;
} & Record<string, unknown>;
